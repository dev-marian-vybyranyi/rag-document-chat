const bytes = (...values: number[]) => values;

const padded = (head: number[], size = 64) =>
  Buffer.from([...head, ...Array.from({ length: Math.max(0, size - head.length) }, () => 0)]);

export const audioSamples = {
  mp3: () => padded(bytes(0x49, 0x44, 0x33, 4, 0, 0)),
  mp3WithoutTag: () => padded(bytes(0xff, 0xfb, 0x90, 0x00)),
  wav: () =>
    padded(bytes(0x52, 0x49, 0x46, 0x46, 0x24, 0, 0, 0, 0x57, 0x41, 0x56, 0x45, 0x66, 0x6d, 0x74)),
  m4a: () => padded(bytes(0, 0, 0, 0x20, 0x66, 0x74, 0x79, 0x70, 0x4d, 0x34, 0x41, 0x20)),
  webm: () => padded(bytes(0x1a, 0x45, 0xdf, 0xa3, 0x9f)),
};
